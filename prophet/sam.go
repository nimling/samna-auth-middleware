package prophet

import "github.com/labstack/echo/v4"

func RegisterSam(g *echo.Group) {
	user := g.Group("/user")
	user.GET("", GetUsers)
	user.GET("/:id", GetUser)
	user.GET("/:id/asset", GetUserAssets)
	user.GET("/:id/claim", GetUserClaims)
	user.GET("/:id/user", GetUserConnections)
	user.GET("/:id/audit", GetUserAudit)
	user.GET("/:id/relation", GetUserRelations)
	user.GET("/:id/organization", GetUserOrganizations)
	user.GET("/:id/location", GetUserLocations)
	user.POST("", PostUser)
	user.PUT("/:id", PutUser)
	user.PATCH("/:id", PutUser)
	user.DELETE("/:id", DeleteUser)
	user.POST("/token", PostUserToken)
	user.POST("/token/validate", PostUserTokenValidate)
	user.POST("/external", PostUserExternal)

	relation := g.Group("/relation")
	relation.GET("", GetRelations)
	relation.GET("/:id", GetRelation)
	relation.POST("", PostRelation)
	relation.PUT("/:id", PutRelation)
	relation.DELETE("/:id", DeleteRelation)

	org := g.Group("/organization")
	org.GET("", GetOrganizations)
	org.GET("/graph", GetOrganizationGraph)
	org.GET("/:id", GetOrganization)
	org.GET("/:id/asset", GetOrganizationAssets)
	org.GET("/:id/claim", GetOrganizationClaims)
	org.POST("", PostOrganization)
	org.PUT("/:id", PutOrganization)
	org.PATCH("/:id", PutOrganization)
	org.DELETE("/:id", DeleteOrganization)
	org.GET("/:id/audit", GetOrganizationAudit)

	loc := g.Group("/location")
	loc.GET("", GetLocations)
	loc.GET("/:id", GetLocation)
	loc.GET("/:id/asset", GetLocationAssets)
	loc.GET("/:id/claim", GetLocationClaims)
	loc.POST("", PostLocation)
	loc.PUT("/:id", PutLocation)
	loc.PATCH("/:id", PutLocation)
	loc.DELETE("/:id", DeleteLocation)
	loc.GET("/:id/audit", GetLocationAudit)

	claim := g.Group("/claim")
	claim.GET("", GetClaims)
	claim.GET("/graph", GetClaimGraph)
	claim.GET("/:id", GetClaim)
	claim.POST("", PostClaim)
	claim.PUT("/:id", PutClaim)
	claim.PATCH("/:id", PutClaim)
	claim.DELETE("/:id", DeleteClaim)
	claim.POST("/:claim_id/object", PostClaimObject)
	claim.PATCH("/:claim_id/object/:id", PatchClaimObject)
	claim.DELETE("/:claim_id/object/:id", DeleteClaimObject)
	claim.POST("/:claim_id/user", PostClaimUser)
	claim.PATCH("/:claim_id/user/:id", PatchClaimUser)
	claim.DELETE("/:claim_id/user/:id", DeleteClaimUser)
	claim.GET("/:id/audit", GetClaimAudit)

	asset := g.Group("/asset")
	asset.GET("", GetAssets)
	asset.GET("/:id", GetAsset)
	asset.GET("/:id/data", GetAssetData)
	asset.POST("", PostAsset)
	asset.POST("/:id", PostAssetUpload)
	asset.PUT("/:id", PutAsset)
	asset.DELETE("/:id", DeleteAsset)

	app := g.Group("/app")
	app.GET("", GetSamApp)

	sync := g.Group("/sync")
	sync.GET("/snapshot", GetSyncSnapshot)
	sync.GET("/:seq", GetSyncEvents)
	sync.POST("", PostSync)

	client := g.Group("/samna_client")
	client.GET("", GetClients)
	client.GET("/:id", GetClient)
	client.POST("", PostClient)
	client.PUT("/:id", PutClient)
	client.PATCH("/:id", PutClient)
	client.DELETE("/:id", DeleteClient)
	client.POST("/:id/rotate", PostClientRotate)
	client.POST("/:id/claim", PostClientClaim)
	client.DELETE("/:id/claim/:claim_id", DeleteClientClaim)

	secret := g.Group("/secret")
	secret.GET("", GetSecrets)
	secret.GET("/:id", GetSecret)
	secret.POST("", PostSecret)
	secret.PUT("/:id", PutSecret)
	secret.PATCH("/:id", PutSecret)
	secret.DELETE("/:id", DeleteSecret)

	g.GET("/search", GetSearch)
	g.POST("/search", PostSearch)

	code := g.Group("/code")
	code.GET("", GetCodes)
	code.GET("/:code", GetCode)
	code.POST("", PostCode)
	code.PUT("/:id", PutCode)
	code.DELETE("/:id", DeleteCode)

	field := g.Group("/field")
	field.GET("", GetObjectFields)
	field.GET("/:id", GetObjectField)
	field.POST("", PostObjectField)
	field.PUT("/:id", PutObjectField)
	field.DELETE("/:id", DeleteObjectField)
	field.GET("/:id/value", GetUserFields)
	field.POST("/:id/value", PostUserField)
	field.PUT("/:id/value/:value_id", PutUserField)
	field.DELETE("/:id/value/:value_id", DeleteUserField)
}
